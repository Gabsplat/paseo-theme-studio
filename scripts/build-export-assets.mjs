import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve, relative } from "node:path";
const projectDirectory = resolve(new URL("..", import.meta.url).pathname);
const files = {};
async function visit(path) {
  const name = relative(projectDirectory, path).replaceAll("\\", "/");
  if (name in files) return;
  const source = await readFile(path, "utf8");
  files[name] = source;
  for (const match of source.matchAll(/from\s+["'](\.[^"']+)["']/g)) {
    const base = resolve(dirname(path), match[1]);
    let dependency;
    for (const ext of [".ts", ".tsx"]) {
      try {
        await readFile(base + ext);
        dependency = base + ext;
        break;
      } catch {}
    }
    if (!dependency) throw new Error("Missing export dependency " + match[1]);
    await visit(dependency);
  }
}
await visit(resolve(projectDirectory, "client/pack-runtime.tsx"));
await writeFile(
  resolve(projectDirectory, "server/export-assets.ts"),
  "// Generated by scripts/build-export-assets.mjs. Rebuild after renderer changes.\nexport const exportAssets = " +
    JSON.stringify({ files }, null, 2) +
    " as const;\n",
);
console.log("Prepared " + Object.keys(files).length + " validated renderer source assets.");
